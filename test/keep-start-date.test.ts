/**
 * 적용 시작 글자를 지키는 규칙 — 실사고 2026-09-10.
 *
 * 한백이 플러그링크 매트릭스에서 시공비·영업비만 고쳤는데 「단가케이스는 그대로네?」가
 * 됐다. 금액은 저장돼 있었다 — 같이 바뀐 것은 ★적용 시작 글자★였다.
 *
 * 폼은 시작을 startKey 로 접었다 펴므로 「2026년 9월 1일 ~ 12월 31일」이 「2026년 9월 1일」로
 * 줄어든다. 그 글자가 매트릭스의 시기 탭 키라(Grid 의 periods = startDate 문자열 집합),
 * 9월 케이스 9개 중 8개가 새 탭으로 옮겨 가고 원래 탭에는 7·8월 값이 이월돼 보였다.
 */
import { describe, expect, it } from 'vitest';
import { keepStartDate, startKey } from '@/lib/pricing-match';

describe('적용 시작 글자', () => {
  it('★가리키는 날이 같으면 원래 글자를 살린다★ — 기간 표기가 시작일 하나로 줄지 않는다', () => {
    expect(keepStartDate('2026년 9월 1일 ~ 12월 31일', '2026년 9월 1일', 2026))
      .toBe('2026년 9월 1일 ~ 12월 31일');
    expect(keepStartDate('2026년 7월 1일 ~ 8월 31일', '2026년 7월 1일', 2026))
      .toBe('2026년 7월 1일 ~ 8월 31일');
  });

  it('두 글자가 같은 날을 가리킨다 — 그래서 살려도 정렬이 안 흔들린다', () => {
    expect(startKey({ startDate: '2026년 9월 1일 ~ 12월 31일', bizYear: 2026 }))
      .toBe(startKey({ startDate: '2026년 9월 1일', bizYear: 2026 }));
  });

  it('날을 정말 옮겼으면 새 글자를 쓴다', () => {
    expect(keepStartDate('2026년 9월 1일 ~ 12월 31일', '2026년 10월 1일', 2026))
      .toBe('2026년 10월 1일');
    expect(keepStartDate('2026년 하반기', '2026년 9월 1일', 2026)).toBe('2026년 9월 1일');
  });

  it('반기 표기끼리도 같으면 살린다', () => {
    expect(keepStartDate('2026년 하반기', '2026년 하반기', 2026)).toBe('2026년 하반기');
  });

  it('새 케이스에는 원래 글자가 없다 — 지은 것을 그대로 쓴다', () => {
    expect(keepStartDate(undefined, '2026년 9월 1일', 2026)).toBe('2026년 9월 1일');
    expect(keepStartDate('', '2026년 하반기', 2026)).toBe('2026년 하반기');
  });
});
