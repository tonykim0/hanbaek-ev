-- 단가 케이스 이름의 「연동」도 「기설치 연동」으로 (한백 지시 2026-09-07)
--
-- 0062 가 축 값(biz_type·repl_type)을 갈았는데 이름은 손으로 적은 글이라 안 따라왔다.
-- 이름 형식이 「운영사 (기간) | 건물 | N년 교체유형 | 수전방식」이라 교체유형 자리가
-- 이름 안에 글자로 들어 있다 — /pricing 에서 사업구분을 「기설치 연동」으로 걸러 놓고
-- 목록 제목은 「7년 연동」이라 필터와 제목의 말이 달랐다.
--
-- 화면이 만드는 라벨(replLabel)과 앞으로 생성될 이름은 이미 「기설치 연동」이다 —
-- 축을 그대로 쓰기 때문이다. 낡은 것은 저장된 이 6줄과 정의 파일의 손글씨뿐이었다.
--
-- 「년 연동」만 겨냥한다 — 「기설치 연동」에는 그 조각이 없어서 두 번 돌려도 안전하다.

update pricing_rules
   set case_name = replace(case_name, '년 연동', '년 기설치 연동')
 where case_name like '%년 연동%';
