-- 이브이솔루션 현장의 시공사를 「이브이솔루션 (영업)」으로 — 턴키업체로 지급 · 세금계산서를 다 맡는다 (한백 지시 2026-11-18)
--
-- ★왜★ 「이브이솔루션(영업)이 턴키업체역할을 해서 지급관리의 모든걸 담당해. 수금부터 세금계산서 발행까지. 그래서
-- 이브이솔루션(시공)에 지급할 건은 다 이브이솔루션은 (영업) 으로 넘어가게돼.」
-- 시공비의 지급처는 현장의 시공사다(원장에 지급처 칸이 없다 — lib/payout-board payoutsOfDetail · 배치 = 지급처 × 구분 × 지급일).
-- 시공사가 「이브이솔루션 (시공)」인 채로는 시공비 배치 · 거래명세서 · 세금계산서가 그 이름으로 서고, 턴키업체인 영업 계정은 지급관리에서
-- 영업비만 본다. 시공사를 영업 쪽으로 옮기면 두 자리가 같은 회사인 턴키 현장이 된다(협력사가 직접 접수하면 원래 이렇게 선다 —
-- pg-store projectRowOf). 운영 2026-11-17 백업: 시공사가 「이브이솔루션 (시공)」인 현장 9곳 · 영업사는 전부 「이브이솔루션 (영업)」 ·
-- 시공비 원장 줄 0건 · 그 이름의 최종 확정 · 세금계산서 0건 — 옮겨지는 지난 돈이 없다.
--
-- 막는 것은 현장 상세의 「시공사 지정」(pg-store setOrgs)과 같다 — 시공비가 한 번이라도 나간 현장은 그 이름으로 거래명세서에 묶여 있어
-- 옮기지 않는다(감사 M3). 단가는 그대로다 — 단가 맞추기는 소속을 보지 않는다(lib/pricing-match). 패스스루는 화두에너지솔루션만이다.
-- 「이브이솔루션 (시공)」 계정은 0137 이 (영업) 소속의 「정산 안 보는」 시공 계정으로 옮긴다 — 현장은 다 보고 시공을 적되 돈은 안 본다.
--
-- 멱등: 시공사가 아직 「이브이솔루션 (시공)」인 줄만 옮긴다 — 다시 돌면 0건.

with moved as (
  update projects p
     set gc_org = '이브이솔루션 (영업)'
   where p.gc_org = '이브이솔루션 (시공)'
     and not exists (select 1 from payout_entries e where e.project_id = p.id and e.kind = '시공비')
  returning p.id
)
insert into audit_log (id, project_id, actor, action, field, old_value, new_value)
select gen_random_uuid()::text, moved.id, '마이그레이션 0136 (한백 2026-11-18)', '시공사 지정', 'gcOrg',
       '이브이솔루션 (시공)', '이브이솔루션 (영업)'
  from moved;
