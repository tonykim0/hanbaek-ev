-- 플러그링크 9월 케이스의 적용 시작 글자를 되돌린다 (한백 지적 2026-09-10)
--
-- 「매트릭스 시공비랑 영업비를 수정했는데 단가케이스는 그대로네?」 — 금액은 저장돼
-- 있었다. 같이 바뀐 것이 ★적용 시작 글자★다:
--   「2026년 9월 1일 ~ 12월 31일」 → 「2026년 9월 1일」
--
-- 케이스 폼이 시작을 startKey(연·월·일)로 접었다 폈다 — 기간 표기의 뒷부분이 그때
-- 사라진다. 그 글자는 표시용이 아니라 ★매트릭스의 시기 탭 키★이고(Grid 의 periods 는
-- startDate 문자열 집합이다) 케이스 이름에도 박힌다. 그래서 9월 케이스 9개 중 손댄 8개가
-- 새 탭으로 옮겨 가고, 원래 탭에는 7·8월 케이스가 이월돼 보였다 — 고친 값이 안 먹은 것처럼.
--
-- ★뿌리는 같은 배포에서 막았다★ (lib/pricing-match keepStartDate): 가리키는 날이 같으면
-- 원래 글자를 살린다. 이 파일은 이미 갈라진 8건을 한 탭으로 되돌린다.
--
-- ★금액은 건드리지 않는다★ — 한백이 고친 값이 맞다(시공 95→100만, 영업은 그만큼 내려
-- 받는 총액은 그대로). 되돌리는 것은 시기 글자와 이름의 그 부분뿐이다.
-- 옛 값일 때만 고치므로 다시 돌아도 안전하다.

update pricing_rules
set start_date = '2026년 9월 1일 ~ 12월 31일',
    case_name  = replace(case_name, '(2026년 9월 1일)', '(2026년 9월 1일 ~ 12월 31일)')
where cpo = '플러그링크'
  and start_date = '2026년 9월 1일';

-- 되돌린 뒤 9월 케이스가 한 탭에 모여 있어야 한다 — 아니면 배포를 멈춘다
do $$
declare n int;
begin
  select count(distinct start_date) into n
    from pricing_rules where cpo = '플러그링크' and start_date like '2026년 9월%';
  if n > 1 then
    raise exception '플러그링크 9월 케이스의 적용 시작이 % 가지로 갈려 있습니다 — 시기 탭이 나뉩니다', n;
  end if;
end $$;
