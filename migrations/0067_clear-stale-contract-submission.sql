-- 반려보다 오래된 접수 선언을 지운다 — 「반려한 항목들을 다 채우고 계약 재검토 요청을
-- 눌러야만 계약검토 단계로」(한백 지시 2026-09-08)
--
-- 규칙이 바뀌었다: 보완요청·반려가 접수 선언(contract_submitted_at)을 무효로 만들고,
-- 협력사가 다시 「계약 재검토 요청」을 눌러야 검토에 선다(lib/board · lib/data/store 의
-- applyReviewSideEffects·applyAskSideEffects). 그런데 그 규칙 이전에 반려된 현장에는
-- ★옛 선언이 그대로 남아 있다★ — 그대로 두면 협력사가 파일만 갈아 끼우는 순간 요청 없이
-- 검토로 넘어가고(옛 동작), 화면은 요청 단추를 감춘 채 옛 날짜로 「재검토 요청 완료」라
-- 적는다. 선언이 반려보다 앞서면 그 선언은 이미 참이 아니다 — 지운다.
--
-- 실측 2026-09-08(읽기 전용): 보완요청 이력 90곳 중 낡은 선언 65곳 + 같은 날 2곳.
--   그중 계약 확인이 끝난 15곳은 ★건드리지 않는다★ — 한백이 이미 확인했으니 선언을
--   되묻을 일이 없다(확인 없이 착공으로 못 가므로 착공 뒤 현장도 여기서 걸러진다).
--   반려가 남은 48곳(+같은 날 2곳)은 칸이 계약보완 그대로고 요청 단추가 새로 선다.
--   반려가 다 풀렸는데 요청을 안 누른 2곳(광교경동해피리움·예산 풍진)만 계약검토에서
--   계약보완으로 내려간다 — 협력사가 누르면 다시 올라온다.
-- 같은 날(<=)도 지운다 — 날짜로 앞뒤를 못 가르는데, 그 2곳은 반려가 남아 있어 어차피
-- 다시 눌러야 한다. 반려 뒤에 다시 요청한 19곳(선언 > 반려)은 그대로다.
update projects
   set contract_submitted_at = null
 where contract_fix_asked_at is not null
   and contract_submitted_at is not null
   and contract_submitted_at <= contract_fix_asked_at
   and contract_confirmed_at is null;
