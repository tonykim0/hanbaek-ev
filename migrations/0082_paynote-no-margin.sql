do $$
declare
  bad text;
begin
  select string_agg(project_id, ', ') into bad
    from settlements
   where pay_note like '%한백 마진%' or pay_note like '%받는 단가%';
  if bad is not null then
    raise exception '협력사가 보는 정산 메모에 원가(한백 마진·받는 단가)가 적힌 현장: %', bad;
  end if;
end $$;
